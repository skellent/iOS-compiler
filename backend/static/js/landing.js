function applyTheme(theme) {
  document.documentElement.dataset.theme = ["auto", "light", "dark"].includes(theme) ? theme : "auto";
}

function detectLanguage() {
  const nav = (typeof navigator !== "undefined" ? navigator.language : "en") || "en";
  const lower = nav.toLowerCase();
  if (lower.startsWith("pt")) return lower === "pt-pt" || lower.startsWith("pt-pt") ? "pt-PT" : "pt-BR";
  const prefixMatch = { es: "es", fr: "fr", de: "de", it: "it", ru: "ru", zh: "zh", ja: "ja", ko: "ko", hi: "hi" };
  return prefixMatch[lower.slice(0, 2)] ?? "en";
}

function applyLanguage(lang) {
  const code = SUPPORTED.includes(lang) ? lang : "en";
  const strings = STRINGS[code];
  document.documentElement.lang = code;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const value = strings[el.dataset.i18n];
    if (value) el.textContent = value;
  });
}

function init() {
  applyTheme(localStorage.getItem(THEME_KEY) || "auto");
  document.getElementById("theme-select").value = document.documentElement.dataset.theme;

  const langSelect = document.getElementById("lang-select");
  LANGUAGES.forEach(({ code, label }) => {
    const option = document.createElement("option");
    option.value = code;
    option.textContent = label;
    langSelect.appendChild(option);
  });
  const currentLang = localStorage.getItem(LANG_KEY) || detectLanguage();
  langSelect.value = currentLang;
  applyLanguage(currentLang);

  document.getElementById("theme-select").addEventListener("change", (event) => {
    localStorage.setItem(THEME_KEY, event.target.value);
    applyTheme(event.target.value);
  });
  langSelect.addEventListener("change", (event) => {
    localStorage.setItem(LANG_KEY, event.target.value);
    applyLanguage(event.target.value);
  });

  const settingsDialog = document.getElementById("settings-dialog");
  document.getElementById("settings-btn").addEventListener("click", () => settingsDialog.showModal());
  settingsDialog.addEventListener("click", (event) => {
    if (event.target === settingsDialog) settingsDialog.close();
  });
}

init();
